import base64
import json
from dataclasses import field

from pydantic import SecretStr
from pydantic.dataclasses import dataclass


class MissingUserError(BaseException):
    """Raised when no user object is passed"""


@dataclass
class UnimiUser:
    """Class representing Unimi students and their informations"""

    email: str
    password: SecretStr  # so it wont be printed
    user_type:str = "S"  # type student, will try to expand this class to every type of user
    # we get these from the token after login
    name: str = field(init=False)
    surname: str = field(init=False)
    fullname: str = field(init=False)
    tax_id: str = field(init=False)
    matriculation_number: str | None = field(init=False)
    phone_number: str | None = field(init=False)

    def _decode_jwt_payload(self, token: str) -> dict:

        payload_b64 = token.split(".")[1]
        # restore missing base64 padding ('=') so length is divisible by 4
        padding = "=" * (-len(payload_b64) % 4)
        decoded_bytes = base64.urlsafe_b64decode(payload_b64 + padding)
        return json.loads(decoded_bytes.decode("utf-8"))

    def get_data_from_jsw(self, jsw_token: str) -> None:
        """Populates the user data from the jsw token

        Parameters
        ----------
        jsw_token : str
            token generated by the server
        """
        user_data = self._decode_jwt_payload(jsw_token)

        self.name = user_data["name"]
        self.surname = user_data["surname"]
        self.fullname = user_data["cognome_nome"]
        self.tax_id = user_data["codice_fiscale"]
        # they might be set to null/None
        self.phone_number = user_data["phone"]
        self.matriculation_number = user_data["matricola"]
